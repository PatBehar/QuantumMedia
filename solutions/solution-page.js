const buildPageCopy = (language) => {
  const content = solution[language];
  const relatedOne = solutionCatalog[solution.related[0]][language];
  const relatedTwo = solutionCatalog[solution.related[1]][language];
  const dictionary = {
    ...sharedSolutionCopy[language],
    title: `${content.name} | Quantum Media`,
    description: content.intro,
    solutionName: content.name,
    heroStatement: content.statement,
    heroCopy: content.intro,
    startSolutionProject: content.button,
    visualCopy: content.challenge,
    challengeCopy: content.challenge,
    approachCopy: content.approach,
    ctaTitle: content.ctaTitle,
    ctaCopy: content.ctaCopy,
    relatedOne: relatedOne.name,
    relatedTwo: relatedTwo.name
  };

  content.useCases.forEach((item, index) => {
    dictionary[`useCase${index + 1}`] = item;
  });
  content.improvements.forEach((item, index) => {
    dictionary[`improvement${index + 1}`] = item;
  });
  content.capabilities.forEach((item, index) => {
    dictionary[`detailCapability${index + 1}`] = item;
  });

  return dictionary;
};

